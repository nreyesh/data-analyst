"""Isolated subprocess execution sandbox for LLM-generated Matplotlib scripts."""

from __future__ import annotations

import json
import logging
import os
import shutil
import subprocess
import sys
import uuid
from pathlib import Path
from typing import Any

from analytics.config import get_analytics_settings

logger = logging.getLogger("analytics.sandbox")


class SandboxExecutionResult:
    """Result returned by sandbox script runner."""

    def __init__(
        self,
        success: bool,
        chart_path: Path | None = None,
        error_message: str | None = None,
        stdout: str = "",
        stderr: str = "",
        duration_seconds: float = 0.0,
    ) -> None:
        self.success = success
        self.chart_path = chart_path
        self.error_message = error_message
        self.stdout = stdout
        self.stderr = stderr
        self.duration_seconds = duration_seconds


def run_plotting_sandbox(
    script_code: str,
    dataset: list[dict[str, Any]],
    output_filename: str | None = None,
    timeout_seconds: int | None = None,
) -> SandboxExecutionResult:
    """Safely execute generated Matplotlib script in an isolated subprocess.

    Args:
        script_code: Python code string generated by LLM visualizer.
        dataset: In-memory records passed as 'dataset.json' in scratch directory.
        output_filename: Optional permanent name for destination PNG.
        timeout_seconds: Optional timeout override in seconds (defaults to settings).

    Returns:
        SandboxExecutionResult containing chart path on success, or captured error message.
    """
    settings = get_analytics_settings()
    settings.ensure_directories()

    timeout = timeout_seconds or settings.sandbox_timeout_seconds
    run_id = uuid.uuid4().hex[:12]
    run_dir = settings.scratch_dir / f"run_{run_id}"
    run_dir.mkdir(parents=True, exist_ok=True)

    dataset_path = run_dir / "dataset.json"
    script_path = run_dir / "script.py"
    expected_output_png = run_dir / "output.png"

    # 1. Pre-inject sanitized dataset and script
    with open(dataset_path, "w", encoding="utf-8") as f:
        json.dump(dataset, f, indent=2, ensure_ascii=False)

    with open(script_path, "w", encoding="utf-8") as f:
        f.write(script_code)

    # 2. Build isolated headless environment
    safe_env = {
        "MPLBACKEND": "Agg",
        "PATH": os.environ.get("PATH", ""),
        "SYSTEMROOT": os.environ.get("SYSTEMROOT", ""),
        "TMP": str(run_dir),
        "TEMP": str(run_dir),
    }
    # Preserve virtual environment site-packages if active
    if "VIRTUAL_ENV" in os.environ:
        safe_env["VIRTUAL_ENV"] = os.environ["VIRTUAL_ENV"]

    import time
    start_time = time.perf_counter()

    try:
        proc = subprocess.run(
            [sys.executable, "-u", str(script_path.name)],
            cwd=str(run_dir),
            env=safe_env,
            timeout=timeout,
            capture_output=True,
            text=True,
        )
        duration = round(time.perf_counter() - start_time, 2)

        if proc.returncode != 0:
            error_msg = proc.stderr.strip() or f"Script exited with error code {proc.returncode}"
            logger.warning("Sandbox execution failed in %s: %s", run_dir.name, error_msg)
            return SandboxExecutionResult(
                success=False,
                error_message=f"SubprocessError (exit code {proc.returncode}):\n{error_msg}",
                stdout=proc.stdout,
                stderr=proc.stderr,
                duration_seconds=duration,
            )

        if not expected_output_png.exists():
            return SandboxExecutionResult(
                success=False,
                error_message="Script exited successfully but did not produce 'output.png'.",
                stdout=proc.stdout,
                stderr=proc.stderr,
                duration_seconds=duration,
            )

        # 3. Move chart to permanent destination
        final_filename = output_filename or f"chart_{run_id}.png"
        if not final_filename.endswith(".png"):
            final_filename += ".png"

        destination = settings.charts_dir / final_filename
        shutil.copy2(expected_output_png, destination)

        # Clean up scratch run directory on success
        try:
            shutil.rmtree(run_dir, ignore_errors=True)
        except Exception:
            pass

        return SandboxExecutionResult(
            success=True,
            chart_path=destination,
            stdout=proc.stdout,
            stderr=proc.stderr,
            duration_seconds=duration,
        )

    except subprocess.TimeoutExpired as exc:
        duration = round(time.perf_counter() - start_time, 2)
        logger.warning("Sandbox execution timed out after %ds in %s", timeout, run_dir.name)
        # Attempt to kill leftover processes in scratch dir
        shutil.rmtree(run_dir, ignore_errors=True)
        return SandboxExecutionResult(
            success=False,
            error_message=f"TimeoutError: Script execution exceeded hard ceiling of {timeout} seconds.",
            stdout=exc.stdout.decode() if isinstance(exc.stdout, bytes) else (exc.stdout or ""),
            stderr=exc.stderr.decode() if isinstance(exc.stderr, bytes) else (exc.stderr or ""),
            duration_seconds=duration,
        )
    except Exception as exc:
        duration = round(time.perf_counter() - start_time, 2)
        logger.error("Unexpected error in sandbox: %s", exc, exc_info=True)
        shutil.rmtree(run_dir, ignore_errors=True)
        return SandboxExecutionResult(
            success=False,
            error_message=f"SandboxRunnerException: {exc}",
            duration_seconds=duration,
        )
